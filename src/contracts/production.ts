import type { IsoDate } from "./common";

/**
 * Production facet (panel-api `production` module). Two modes, told apart by `source`: CLICKUP while a
 * list is linked (status, phase, book type and dates are read from ClickUp, read-only) and MANUAL
 * otherwise (those fields are typed in by hand). `authorName` is editable in both.
 */

/** Calendar date "yyyy-mm-dd" (not a timestamp): format it without timezone conversion. */
export type CalendarDate = string;

export const PRODUCTION_STATUSES = ["NOT_STARTED", "IN_PRODUCTION", "FINISHED"] as const;
export type ProductionStatus = (typeof PRODUCTION_STATUSES)[number];

/** CLICKUP while a list is linked, MANUAL otherwise. */
export type ProductionSource = "CLICKUP" | "MANUAL";

/** Phase that goes with FINISHED (panel-api `manual-state.ts`). */
export const PUBLISHED_PHASE_CODE = "PUBLISHED";

export const BOOK_TYPES = ["ACADEMIC", "TEXTBOOK"] as const;
export type BookType = (typeof BOOK_TYPES)[number];

/** @api existing — item of GET /production-phases (seeded catalog, ordered by sortOrder). */
export interface ProductionPhase {
  id: string;
  code: string;
  label: string;
  sortOrder: number;
}

/** @api existing — ProductionPhaseRefDto. */
export interface ProductionPhaseRef {
  code: string;
  label: string;
}

/** @api existing — ProductionDetailDto: every /projects/:projectId/production endpoint. */
export interface ProductionDetail {
  id: string;
  projectId: string;
  /** Random "XXXX-XXXX", generated by the API. Read-only. */
  publicCode: string;
  authorName: string | null;
  clickupListId: string | null;
  bookType: BookType | null;
  source: ProductionSource;
  status: ProductionStatus;
  currentPhase: ProductionPhaseRef | null;
  /** ClickUp task name; always null in MANUAL mode. */
  currentStageName: string | null;
  currentStageDueDate: CalendarDate | null;
  estimatedEndDate: CalendarDate | null;
  lastSyncedAt: IsoDate | null;
  createdAt: IsoDate;
  updatedAt: IsoDate;
}

/**
 * @api existing — item of GET /productions (a plain array, ordered by project title).
 * No `id`, `clickupListId` or `createdAt`: the detail is loaded when a production is opened.
 */
export interface ProductionListItem {
  projectId: string;
  projectTitle: string;
  publicCode: string;
  authorName: string | null;
  source: ProductionSource;
  status: ProductionStatus;
  bookType: BookType | null;
  currentPhase: ProductionPhaseRef | null;
  currentStageName: string | null;
  currentStageDueDate: CalendarDate | null;
  estimatedEndDate: CalendarDate | null;
  lastSyncedAt: IsoDate | null;
  updatedAt: IsoDate;
}

/**
 * @api existing — PUT /projects/:projectId/production (UpsertProductionDto). Absent = unchanged, null = clear.
 * A `clickupListId` (digits only) validates the list against ClickUp and syncs it right away; `null` unlinks
 * (the production turns MANUAL and keeps its last data). The manual fields are only accepted while the
 * production is not linked after the request (else 409 PRODUCTION_MANAGED_BY_CLICKUP). Status and phase
 * follow manual-state rules: PUBLISHED ⇔ FINISHED, NOT_STARTED has no phase, IN_PRODUCTION any other phase
 * or none; sending both requires them to agree (else 400 PRODUCTION_INCONSISTENT_STATE).
 */
export interface UpsertProductionRequest {
  authorName?: string | null;
  clickupListId?: string | null;
  bookType?: BookType | null;
  /** Never null. */
  status?: ProductionStatus;
  currentPhaseCode?: string | null;
  currentStageDueDate?: CalendarDate | null;
  estimatedEndDate?: CalendarDate | null;
}

/** @api existing — machine `code` of production errors (`production-errors.ts`). */
export const PRODUCTION_ERROR_CODES = [
  "PRODUCTION_ALREADY_EXISTS",
  "PRODUCTION_NOT_FOUND",
  "PRODUCTION_MANAGED_BY_CLICKUP",
  "PRODUCTION_PHASE_NOT_FOUND",
  "PRODUCTION_INCONSISTENT_STATE",
  "PRODUCTION_NOT_LINKED",
  "CLICKUP_LIST_ALREADY_LINKED",
  "CLICKUP_LIST_NOT_FOUND",
  "CLICKUP_LIST_NOT_IN_PRODUCTION",
  "CLICKUP_LIST_UNMAPPED_STAGE",
  "CLICKUP_UNAVAILABLE",
] as const;
export type ProductionErrorCode = (typeof PRODUCTION_ERROR_CODES)[number];
